CREATE OR REPLACE VIEW FRAUD_DETECTION_DB.STREAMING.FRAUD_ALERTS AS
SELECT
    TRANSACTION_ID,
    TIME,
    AMOUNT,
    PREDICTION,
    FRAUD_PROBABILITY,
    CREATED_AT,
    CASE
        WHEN FRAUD_PROBABILITY >= 0.80 THEN 'HIGH RISK'
        WHEN FRAUD_PROBABILITY >= 0.50 THEN 'MEDIUM RISK'
        ELSE 'LOW RISK'
    END AS RISK_LEVEL
FROM FRAUD_DETECTION_DB.STREAMING.FRAUD_TRANSACTIONS
WHERE PREDICTION = 1
   OR FRAUD_PROBABILITY >= 0.50;



SELECT *
FROM FRAUD_DETECTION_DB.STREAMING.FRAUD_ALERTS
ORDER BY FRAUD_PROBABILITY DESC;


SELECT
    COUNT(*) AS TOTAL_TRANSACTIONS,
    COUNT_IF(PREDICTION = 1) AS DETECTED_FRAUD,
    COUNT_IF(FRAUD_PROBABILITY >= 0.50) AS HIGH_PROBABILITY
FROM FRAUD_DETECTION_DB.STREAMING.FRAUD_TRANSACTIONS;


SELECT *
FROM FRAUD_DETECTION_DB.STREAMING.FRAUD_TRANSACTIONS
ORDER BY CREATED_AT DESC
LIMIT 10;


SELECT
    COUNT(*) AS TOTAL_TRANSACTIONS,
    SUM(IFF(PREDICTION = 1, 1, 0)) AS DETECTED_FRAUD,
    ROUND(AVG(FRAUD_PROBABILITY), 6) AS AVG_FRAUD_PROBABILITY
FROM FRAUD_DETECTION_DB.STREAMING.FRAUD_TRANSACTIONS;

