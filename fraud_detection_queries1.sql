CREATE OR REPLACE PROCEDURE FRAUD_DETECTION_DB.STREAMING.RUN_FRAUD_PREDICTION()
RETURNS VARCHAR
LANGUAGE SQL
AS
$$
BEGIN

    INSERT INTO FRAUD_DETECTION_DB.STREAMING.FRAUD_TRANSACTIONS (
        TIME,
        V1, V2, V3, V4, V5, V6, V7, V8, V9, V10,
        V11, V12, V13, V14, V15, V16, V17, V18, V19, V20,
        V21, V22, V23, V24, V25, V26, V27, V28,
        AMOUNT,
        PREDICTION,
        FRAUD_PROBABILITY
    )
    SELECT
        TIME,
        V1, V2, V3, V4, V5, V6, V7, V8, V9, V10,
        V11, V12, V13, V14, V15, V16, V17, V18, V19, V20,
        V21, V22, V23, V24, V25, V26, V27, V28,
        AMOUNT,
        MODEL(
            FRAUD_DETECTION_DB.ML.FRAUD_XGBOOST_MODEL,
            V2
        )!PREDICT(
            TIME,
            V1, V2, V3, V4, V5, V6, V7, V8, V9, V10,
            V11, V12, V13, V14, V15, V16, V17, V18, V19, V20,
            V21, V22, V23, V24, V25, V26, V27, V28,
            AMOUNT
        ):output_feature_0::NUMBER,
        MODEL(
            FRAUD_DETECTION_DB.ML.FRAUD_XGBOOST_MODEL,
            V2
        )!PREDICT_PROBA(
            TIME,
            V1, V2, V3, V4, V5, V6, V7, V8, V9, V10,
            V11, V12, V13, V14, V15, V16, V17, V18, V19, V20,
            V21, V22, V23, V24, V25, V26, V27, V28,
            AMOUNT
        ):output_feature_1::FLOAT
    FROM FRAUD_DETECTION_DB.STREAMING.FRAUD_TRANSACTION_STREAM
    WHERE METADATA$ACTION = 'INSERT';

    RETURN 'Fraud prediction procedure completed';

END;
$$;

CALL FRAUD_DETECTION_DB.STREAMING.RUN_FRAUD_PREDICTION();

