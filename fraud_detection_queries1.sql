CREATE OR REPLACE PROCEDURE CHECK_FRAUD_STREAM()
RETURNS STRING
LANGUAGE SQL
AS
$$
DECLARE
    transaction_count INTEGER;
BEGIN

    SELECT COUNT(*)
    INTO :transaction_count
    FROM FRAUD_TRANSACTION_STREAM;

    RETURN 'New transactions detected: ' || transaction_count;

END;
$$;

CALL CHECK_FRAUD_STREAM();

